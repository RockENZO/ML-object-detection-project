"""Verify the exact flat test split produced by prepare_grouped_split.py."""
from pathlib import Path
from prepare_grouped_split import digest


def verify_test_inputs(dataset, split):
    # The model loader follows YAML's test path, not this manifest's split names.
    if dataset.get('test') != 'test/images':
        raise ValueError('Evaluation requires test: test/images from prepare_grouped_split.py')
    root_value = dataset.get('path')
    if not isinstance(root_value, str) or not Path(root_value).is_absolute():
        raise ValueError('Evaluation requires the absolute dataset path generated by prepare_grouped_split.py')
    root = Path(root_value)
    if not isinstance(split, dict) or not isinstance(split.get('records'), list):
        raise ValueError('Invalid grouped split manifest records')
    records = split['records']
    if any(not isinstance(r, dict) or r.get('split') not in ('train', 'val', 'test')
           or not isinstance(r.get('group'), str) or not r['group'] for r in records):
        raise ValueError('Invalid grouped split manifest record')
    test_records = [r for r in records if r['split'] == 'test']
    if not test_records:
        raise ValueError('Test split is empty')
    test_groups = {r['group'] for r in test_records}
    if test_groups & {r['group'] for r in records if r['split'] != 'test'}:
        raise ValueError('Test groups overlap training/validation groups in manifest')
    expected = {'images': set(), 'labels': set()}
    for record in test_records:
        for key in ('image', 'label'):
            if not isinstance(record.get(key), str) or not record[key]:
                raise ValueError('Invalid image/label name in manifest')
        image, label = Path(record['image']).name, Path(record['label']).name
        if Path(image).suffix.lower() not in ('.jpg', '.jpeg', '.png'):
            raise ValueError('Unsupported test image in manifest')
        if label != Path(image).stem + '.txt':
            raise ValueError('Test label name differs from the image loader pairing')
        for kind, key, name in [('images', 'image', image), ('labels', 'label', label)]:
            if name in expected[kind]:
                raise ValueError('Duplicate test artifact in manifest: ' + name)
            expected[kind].add(name)
            directory = root / 'test' / kind
            artifact = directory / name
            if (root.is_symlink() or (root / 'test').is_symlink() or directory.is_symlink()
                    or artifact.is_symlink() or not artifact.is_file()
                    or digest(artifact) != record.get(key + '_sha256')):
                raise ValueError('Test artifact differs from split manifest: ' + str(artifact))
    for kind, names in expected.items():
        directory = root / 'test' / kind
        # Generated splits are flat. Reject subdirectories as the loader recurses.
        actual = list(directory.iterdir())
        if any(p.is_symlink() or not p.is_file() for p in actual) or {p.name for p in actual} != names:
            raise ValueError('Test directory membership differs from split manifest: ' + str(directory))
    return test_records
